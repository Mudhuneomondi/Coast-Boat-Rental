#!/usr/bin/env node
// Build step:  npm run build      → vendors libraries, compiles Tailwind, writes SRI hashes
//              npm run verify     → fails (exit 1) if any vendored file / SRI hash is out of date (use in CI)
import { createHash } from 'node:crypto';
import { cpSync, mkdirSync, readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root  = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const nm    = (p) => join(root, 'node_modules', p);
const out   = (p) => join(root, 'vendor', p);

function copy(from, to) {
  mkdirSync(dirname(to), { recursive: true });
  cpSync(from, to);
}

if (!check) {
  // 1. libraries come from the pinned, lock-filed npm packages (never from a CDN at run time)
  copy(nm('@supabase/supabase-js/dist/umd/supabase.js'), out('supabase.js'));
  copy(nm('chart.js/dist/chart.umd.min.js'),             out('chart.umd.min.js'));
  copy(nm('@fortawesome/fontawesome-free/css/all.min.css'), out('fontawesome/css/all.min.css'));
  for (const f of readdirSync(nm('@fortawesome/fontawesome-free/webfonts')).filter(f => f.endsWith('.woff2'))) {
    copy(nm('@fortawesome/fontawesome-free/webfonts/' + f), out('fontawesome/webfonts/' + f));
  }
  // 2. Tailwind is compiled ahead of time (no runtime compiler → strict CSP possible)
  execFileSync(process.execPath, [nm('@tailwindcss/cli/dist/index.mjs'),
    '-i', join(root, 'css/tailwind.input.css'), '-o', out('tailwind.css'), '--minify'],
    { stdio: 'inherit', cwd: root });
}

// 3. Subresource Integrity: sha384 of every local asset referenced by index.html
const htmlPath = join(root, 'index.html');
let html = readFileSync(htmlPath, 'utf8');
let stale = 0;
html = html.replace(/<(script|link)\b[^>]*?(?:src|href)="((?:vendor|css|js)\/[^"]+)"[^>]*>/g, (tag, _kind, path) => {
  const file = join(root, path);
  if (!existsSync(file)) { console.error('missing file for', path); stale++; return tag; }
  const hash = 'sha384-' + createHash('sha384').update(readFileSync(file)).digest('base64');
  let t = tag.replace(/\s+integrity="[^"]*"/, '').replace(/\s+crossorigin="[^"]*"/, '');
  t = t.replace(/\s*\/?>$/, m => ` integrity="${hash}" crossorigin="anonymous"${m.trim() === '/>' ? ' />' : '>'}`);
  if (t !== tag) stale++;
  return t;
});
// 4. Security headers: index.html's <meta> CSP is the single source of truth.
//    _headers (Netlify / Cloudflare Pages) and vercel.json are GENERATED from it, so they cannot drift.
const csp = (html.match(/http-equiv="Content-Security-Policy"\s+content="([^"]+)"/) || [])[1];
if (!csp) { console.error('✗ CSP <meta> tag not found in index.html'); process.exit(1); }
const headers = {
  'Content-Security-Policy': csp + "; frame-ancestors 'none'",       // frame-ancestors only works as an HTTP header
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'DENY',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()',
  'Strict-Transport-Security': 'max-age=63072000; includeSubDomains',
  'Cross-Origin-Opener-Policy': 'same-origin',
};
const headersFile = '# GENERATED by scripts/build.mjs from the CSP in index.html — do not edit by hand.\n/*\n' +
  Object.entries(headers).map(([k, v]) => `  ${k}: ${v}`).join('\n') + '\n';
const vercelFile = JSON.stringify({ headers: [{ source: '/(.*)', headers: Object.entries(headers).map(([key, value]) => ({ key, value })) }] }, null, 2) + '\n';
for (const [name, body] of [['_headers', headersFile], ['vercel.json', vercelFile]]) {
  const f = join(root, name);
  if (check) { if (!existsSync(f) || readFileSync(f, 'utf8') !== body) { console.error(`✗ ${name} is out of date — run "npm run build"`); stale++; } }
  else writeFileSync(f, body);
}

if (check) {
  if (stale) { console.error(`✗ ${stale} SRI hash(es) out of date — run "npm run build" and commit.`); process.exit(1); }
  console.log('✓ all SRI hashes match the files on disk');
} else {
  writeFileSync(htmlPath, html);
  console.log(`✓ vendored libraries, compiled Tailwind, updated SRI hashes${stale ? ` (${stale} tag(s) changed)` : ''}`);
}
